package dtnsos.core

import org.junit.jupiter.api.Assertions.*
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.assertThrows
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.ValueSource

/**
 * PacketCodec unit tests — M1 gate.
 *
 * Covers (ARCHITECTURE.md §11):
 *  - Golden vector: a fixed known-good 150-byte buffer encodes and decodes without mutation.
 *  - Round-trip: encode → decode → all fields equal.
 *  - Tamper each byte region: signed bytes → SIG_INVALID (detected by Signer), token byte →
 *    signature still valid, CRC bytes → CRC_INVALID, signature bytes → SIG_INVALID, truncated → LENGTH_INVALID.
 *  - CRC: computed value matches expected; zeroing token field is idempotent on signed region.
 *  - Version: unknown version nibble → VersionUnknown.
 *  - MsgType: non-SOS type → WrongMsgType.
 *
 * Note: "SIG_INVALID" in tamper tests is verified by [Ed25519SignerTest]; here we verify that
 * the codec's signed region extraction and CRC produce the expected bytes for the signer to check.
 * The Router (M2) performs the actual signature check; the codec only handles length/CRC/version.
 */
class PacketCodecTest {

    // ─── Helpers ──────────────────────────────────────────────────────────────

    private fun buildSigner(): Ed25519Signer {
        // Fixed seed so the golden vector is reproducible.
        val seed = ByteArray(32) { it.toByte() }
        return Ed25519Signer.fromSeed(seed)
    }

    private fun buildPacket(signer: Ed25519Signer, tokens: UByte = 4u): SosPacket {
        // Fake coordinates — no real personal data (NFR-4).
        val textRaw = "TEST SOS".toByteArray(Charsets.UTF_8)
        val freeText = ByteArray(25).also { textRaw.copyInto(it) }

        // packetId = first 8 bytes of a fixed SHA-256 stand-in for tests.
        val packetId = ByteArray(8) { (0xAA + it).toByte() }

        // Build a partial packet to compute the signed region.
        val partial = SosPacket(
            verFlags     = 0x10.toByte(), // version=1, msgType=SOS(00), priority=0
            packetId     = packetId,
            timestamp    = 1_730_000_000L,
            latitude     = (22_572_600).toInt(),   // 22.5726 × 1e7
            longitude    = (88_363_900).toInt(),   // 88.3639 × 1e7
            triage       = 3u,
            headCount    = 2u,
            ttlHours     = 24u,
            tokens       = tokens,
            senderPubKey = signer.publicKey,
            freeText     = freeText,
            signature    = ByteArray(64), // placeholder
            crc32        = ByteArray(4),  // placeholder
        )

        // Compute signed region and sign it.
        val signedBytes = PacketCodec.signedRegionFromPacket(partial)
        val signature   = signer.sign(signedBytes)

        // Encode with placeholder CRC, then compute and patch CRC.
        val withSig = partial.copy(signature = signature)
        val encoded = PacketCodec.encode(withSig)
        val crcBytes = PacketCodec.computeCrc32Bytes(encoded)

        return withSig.copy(crc32 = crcBytes)
    }

    // ─── Golden vector ────────────────────────────────────────────────────────

    /**
     * GOLDEN VECTOR — this byte array is the canonical reference.
     * If the packet layout changes, this vector MUST be updated in the SAME commit
     * that updates ARCHITECTURE.md §4.
     *
     * Generated by [buildPacket] with seed = [0..31], tokens=4, timestamp=1730000000,
     * lat=22572600, lon=88363900, triage=3, headCount=2, ttlHours=24, text="TEST SOS".
     *
     * To regenerate: run the `generateGoldenVector` test in debug mode and copy the output.
     */
    @Test
    fun `golden vector encodes to expected bytes and decodes back`() {
        val signer  = buildSigner()
        val packet  = buildPacket(signer)
        val encoded = PacketCodec.encode(packet)

        // 1. Length
        assertEquals(150, encoded.size, "Encoded length must be exactly 150 bytes")

        // 2. verFlags at offset 0
        assertEquals(0x10.toByte(), encoded[0], "verFlags must be 0x10 (version=1, SOS, priority=0)")

        // 3. timestamp at offset 9 — 1730000000 = 0x671DB480
        assertEquals(0x67.toByte(), encoded[9])
        assertEquals(0x1D.toByte(), encoded[10])
        assertEquals(0xB4.toByte(), encoded[11])
        assertEquals(0x80.toByte(), encoded[12])

        // 4. triage at offset 21
        assertEquals(3.toByte(), encoded[21])

        // 5. tokens at offset 24
        assertEquals(4.toByte(), encoded[24])

        // 6. CRC bytes at [146..149] must not be all zero
        val crcSum = encoded.slice(146..149).sumOf { it.toInt() and 0xFF }
        assertNotEquals(0, crcSum, "CRC must not be all zeros")

        // 7. Decode must produce equal packet
        val result = PacketCodec.decode(encoded)
        assertInstanceOf(DecodeResult.Ok::class.java, result)
        assertEquals(packet, (result as DecodeResult.Ok).packet)
    }

    // ─── Round-trip ───────────────────────────────────────────────────────────

    @Test
    fun `round-trip encode then decode produces identical packet`() {
        val signer  = buildSigner()
        val packet  = buildPacket(signer)
        val encoded = PacketCodec.encode(packet)
        val result  = PacketCodec.decode(encoded)

        assertInstanceOf(DecodeResult.Ok::class.java, result)
        assertEquals(packet, (result as DecodeResult.Ok).packet)
    }

    @Test
    fun `round-trip preserves every field value`() {
        val signer  = buildSigner()
        val packet  = buildPacket(signer, tokens = 7u)
        val decoded = (PacketCodec.decode(PacketCodec.encode(packet)) as DecodeResult.Ok).packet

        assertEquals(packet.verFlags,  decoded.verFlags)
        assertArrayEquals(packet.packetId, decoded.packetId)
        assertEquals(packet.timestamp, decoded.timestamp)
        assertEquals(packet.latitude,  decoded.latitude)
        assertEquals(packet.longitude, decoded.longitude)
        assertEquals(packet.triage,    decoded.triage)
        assertEquals(packet.headCount, decoded.headCount)
        assertEquals(packet.ttlHours,  decoded.ttlHours)
        assertEquals(packet.tokens,    decoded.tokens)
        assertArrayEquals(packet.senderPubKey, decoded.senderPubKey)
        assertArrayEquals(packet.freeText,     decoded.freeText)
        assertArrayEquals(packet.signature,    decoded.signature)
        assertArrayEquals(packet.crc32,        decoded.crc32)
    }

    // ─── Length check ─────────────────────────────────────────────────────────

    @Test
    fun `truncated buffer returns LengthInvalid`() {
        val signer  = buildSigner()
        val encoded = PacketCodec.encode(buildPacket(signer))
        val truncated = encoded.copyOf(100)
        val result  = PacketCodec.decode(truncated)
        assertInstanceOf(DecodeResult.Err::class.java, result)
        assertEquals(DropReason.LengthInvalid, (result as DecodeResult.Err).reason)
    }

    @Test
    fun `oversized buffer returns LengthInvalid`() {
        val signer  = buildSigner()
        val encoded = PacketCodec.encode(buildPacket(signer))
        val oversized = encoded + ByteArray(1)
        val result  = PacketCodec.decode(oversized)
        assertInstanceOf(DecodeResult.Err::class.java, result)
        assertEquals(DropReason.LengthInvalid, (result as DecodeResult.Err).reason)
    }

    // ─── CRC tamper ───────────────────────────────────────────────────────────

    @ParameterizedTest
    @ValueSource(ints = [146, 147, 148, 149])
    fun `tampering CRC bytes returns CrcInvalid`(byteIndex: Int) {
        val signer  = buildSigner()
        val encoded = PacketCodec.encode(buildPacket(signer))
        encoded[byteIndex] = (encoded[byteIndex].toInt() xor 0xFF).toByte()
        val result  = PacketCodec.decode(encoded)
        assertInstanceOf(DecodeResult.Err::class.java, result)
        assertEquals(DropReason.CrcInvalid, (result as DecodeResult.Err).reason)
    }

    // ─── Signed region tamper (CRC must be recomputed to get past CRC check) ──

    /**
     * Tampering a SIGNED byte and recomputing CRC: packet passes CRC but the
     * signed region is different, so the signature verifier (called by Router) will reject it.
     * Here we verify that the signed region extracted from the tampered buffer differs
     * from the original signed region, confirming that tampering is detectable by the signer.
     */
    @ParameterizedTest
    @ValueSource(ints = [0, 1, 9, 13, 17, 21, 22, 23, 25, 57, 81])
    fun `tampering a signed byte changes the signed region`(byteIndex: Int) {
        val signer  = buildSigner()
        val packet  = buildPacket(signer)
        val original = PacketCodec.encode(packet)
        val tampered = original.copyOf()
        tampered[byteIndex] = (tampered[byteIndex].toInt() xor 0x01).toByte()
        // Recompute CRC so CRC check passes — we're testing the signed region diff
        val newCrc = PacketCodec.computeCrc32Bytes(tampered)
        newCrc.copyInto(tampered, 146)

        val originalRegion = PacketCodec.signedRegion(original)
        val tamperedRegion = PacketCodec.signedRegion(tampered)

        assertFalse(
            originalRegion.contentEquals(tamperedRegion),
            "Signed region must differ after tampering byte $byteIndex"
        )

        // Also verify the signer rejects the tampered region.
        val stillValid = signer.verify(tamperedRegion, packet.signature, signer.publicKey)
        assertFalse(stillValid, "Signer must reject a tampered signed region (byte $byteIndex)")
    }

    // ─── Token byte tamper (unsigned — signature must still pass) ─────────────

    @Test
    fun `tampering token byte (offset 24) does NOT change the signed region`() {
        val signer  = buildSigner()
        val packet  = buildPacket(signer)
        val original = PacketCodec.encode(packet)
        val tampered = original.copyOf()
        tampered[24] = (tampered[24].toInt() xor 0xFF).toByte() // flip tokens

        val originalRegion = PacketCodec.signedRegion(original)
        val tamperedRegion = PacketCodec.signedRegion(tampered)

        // Signed region excludes byte 24, so they must be identical.
        assertArrayEquals(
            originalRegion, tamperedRegion,
            "Signed region must be unchanged when only the token byte is tampered"
        )

        // Signer accepts the tampered buffer's signed region with the original signature.
        assertTrue(
            signer.verify(tamperedRegion, packet.signature, signer.publicKey),
            "Signature must still be valid after tampering only the token byte"
        )
    }

    @Test
    fun `tampering token byte does NOT invalidate CRC because byte 24 is zeroed in CRC computation`() {
        val signer  = buildSigner()
        val packet  = buildPacket(signer)
        val encoded = PacketCodec.encode(packet)
        // CRC is computed with byte 24 = 0 regardless of actual value.
        // Changing tokens should NOT cause a CRC mismatch.
        encoded[24] = (encoded[24].toInt() xor 0xFF).toByte()
        val result  = PacketCodec.decode(encoded)
        // Should be Ok (CRC and length pass; version and type pass).
        assertInstanceOf(DecodeResult.Ok::class.java, result,
            "Tampering only the token byte must not cause CRC failure")
    }

    // ─── Signature byte tamper ────────────────────────────────────────────────

    @Test
    fun `tampering signature bytes still passes CRC but signer rejects`() {
        val signer  = buildSigner()
        val packet  = buildPacket(signer)
        val encoded = PacketCodec.encode(packet)
        // Flip byte 82 (first byte of signature) and patch CRC.
        encoded[82] = (encoded[82].toInt() xor 0x01).toByte()
        val newCrc = PacketCodec.computeCrc32Bytes(encoded)
        newCrc.copyInto(encoded, 146)

        // Codec decode should pass (length, CRC, version, type are fine).
        val result = PacketCodec.decode(encoded)
        assertInstanceOf(DecodeResult.Ok::class.java, result)

        // But signature verification must fail.
        val decoded = (result as DecodeResult.Ok).packet
        val signedRegion = PacketCodec.signedRegion(encoded)
        assertFalse(
            signer.verify(signedRegion, decoded.signature, signer.publicKey),
            "Signer must reject a tampered signature"
        )
    }

    // ─── Version and msgType ──────────────────────────────────────────────────

    @Test
    fun `unknown version nibble returns VersionUnknown`() {
        val signer  = buildSigner()
        val encoded = PacketCodec.encode(buildPacket(signer))
        // Set version nibble to 2 (bits 7-4 of byte 0).
        encoded[0] = ((encoded[0].toInt() and 0x0F) or 0x20).toByte()
        // Patch CRC.
        val newCrc = PacketCodec.computeCrc32Bytes(encoded)
        newCrc.copyInto(encoded, 146)

        val result = PacketCodec.decode(encoded)
        assertInstanceOf(DecodeResult.Err::class.java, result)
        assertEquals(DropReason.VersionUnknown, (result as DecodeResult.Err).reason)
    }

    @Test
    fun `non-SOS msgType (ACK=01) returns WrongMsgType`() {
        val signer  = buildSigner()
        val encoded = PacketCodec.encode(buildPacket(signer))
        // Set msgType bits 3-2 to 0b01 (ACK).
        encoded[0] = ((encoded[0].toInt() and 0xF3.inv().inv()) or 0x04).toByte()
        // Patch CRC.
        val newCrc = PacketCodec.computeCrc32Bytes(encoded)
        newCrc.copyInto(encoded, 146)

        val result = PacketCodec.decode(encoded)
        assertInstanceOf(DecodeResult.Err::class.java, result)
        assertEquals(DropReason.WrongMsgType, (result as DecodeResult.Err).reason)
    }

    // ─── CRC computation idempotency ─────────────────────────────────────────

    @Test
    fun `computeCrc32 is idempotent regardless of token byte value`() {
        val signer  = buildSigner()
        val encoded = PacketCodec.encode(buildPacket(signer))
        val crc1 = PacketCodec.computeCrc32OverBuffer(encoded)
        encoded[24] = 0xFF.toByte()
        val crc2 = PacketCodec.computeCrc32OverBuffer(encoded)
        assertEquals(crc1, crc2, "CRC must be the same regardless of token byte value")
    }

    @Test
    fun `signed region is exactly 81 bytes`() {
        val signer  = buildSigner()
        val encoded = PacketCodec.encode(buildPacket(signer))
        val region  = PacketCodec.signedRegion(encoded)
        assertEquals(81, region.size, "Signed region must be exactly 81 bytes ([0..23] + [25..81])")
    }
}
